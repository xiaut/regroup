//! Connection configuration module
//!
//! This module handles loading and saving connection configurations.
//! Each connection represents a specific SSH connection between two machines,
//! with its own dedicated SSH key pair for traceability.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use serde::{Serialize, Deserialize};

/// Represents a connection between two machines
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Connection {
    /// Source: format "user@machine"
    pub from: String,
    /// Target user (the user on the target machine)
    pub to: String,
    /// Public key for this connection (generated by regroup)
    pub public_key: String,
    /// Path to the private key file (relative or absolute)
    pub private_key_path: String,
    /// Timestamp when the connection was created
    pub created_at: String,
}

impl Connection {
    /// Creates a new connection
    pub fn new(from: &str, to: &str, public_key: &str, private_key_path: &str, created_at: &str) -> Self {
        Self {
            from: from.to_string(),
            to: to.to_string(),
            public_key: public_key.to_string(),
            private_key_path: private_key_path.to_string(),
            created_at: created_at.to_string(),
        }
    }

    /// Returns the connection file name for the source machine
    pub fn source_filename(&self) -> String {
        // Format: from->to.json
        format!("{}->{}.json", self.from, self.to)
    }

    /// Returns the connection file name for the target machine
    pub fn target_filename(&self) -> String {
        // Format: from->to.json (same as source, but stored in target's directory)
        // We use just the from part as the filename since the target is the directory
        format!("{}->{}.json", self.from, self.to)
    }
}

/// Connection configuration for a machine
#[derive(Clone, Debug, Default)]
pub struct MachineConnections {
    /// Outgoing connections (from this machine)
    pub outgoing: Vec<Connection>,
    /// Incoming connections (to this machine)
    pub incoming: Vec<Connection>,
}

/// Base directory for connection files
pub const CONNECTIONS_DIR: &str = "connections";

/// Loads all connections for a specific machine
pub fn load_machine_connections(config_dir: &Path, machine_name: &str) -> io::Result<MachineConnections> {
    let connections_dir = config_dir.join(CONNECTIONS_DIR).join(machine_name);
    
    if !connections_dir.exists() {
        return Ok(MachineConnections::default());
    }

    let mut outgoing = Vec::new();
    let mut incoming = Vec::new();

    for entry in fs::read_dir(&connections_dir)? {
        let entry = entry?;
        let path = entry.path();
        
        if path.extension().and_then(|s| s.to_str()) == Some("json") {
            if let Ok(content) = fs::read_to_string(&path) {
                if let Ok(conn) = serde_json::from_str::<Connection>(&content) {
                    // Determine if it's outgoing or incoming based on the machine name
                    // Outgoing: from contains machine_name
                    // Incoming: to contains machine_name (or the connection is to this machine)
                    
                    // Parse the filename to understand the connection
                    if let Some(_filename) = path.file_name().and_then(|n| n.to_str()) {
                        // For outgoing: filename is "user@machine->target.json"
                        // For incoming: same file but stored in target's directory
                        // So we check if the connection's "from" matches our machine
                        if conn.from.contains(machine_name) {
                            outgoing.push(conn);
                        } else {
                            incoming.push(conn);
                        }
                    }
                }
            }
        }
    }

    Ok(MachineConnections { outgoing, incoming })
}

/// Saves a connection file for the source machine
pub fn save_source_connection(config_dir: &Path, machine_name: &str, connection: &Connection) -> io::Result<()> {
    let connections_dir = config_dir.join(CONNECTIONS_DIR).join(machine_name);
    fs::create_dir_all(&connections_dir)?;
    
    let filename = connection.source_filename();
    let path = connections_dir.join(filename);
    
    let content = serde_json::to_string_pretty(connection)?;
    fs::write(path, content)?;
    
    Ok(())
}

/// Saves a connection file for the target machine
pub fn save_target_connection(config_dir: &Path, target_machine: &str, connection: &Connection) -> io::Result<()> {
    let connections_dir = config_dir.join(CONNECTIONS_DIR).join(target_machine);
    fs::create_dir_all(&connections_dir)?;
    
    let filename = connection.target_filename();
    let path = connections_dir.join(filename);
    
    let content = serde_json::to_string_pretty(connection)?;
    fs::write(path, content)?;
    
    Ok(())
}

/// Deletes a connection file from the source machine
pub fn delete_source_connection(config_dir: &Path, machine_name: &str, connection: &Connection) -> io::Result<()> {
    let connections_dir = config_dir.join(CONNECTIONS_DIR).join(machine_name);
    let filename = connection.source_filename();
    let path = connections_dir.join(filename);
    
    if path.exists() {
        fs::remove_file(path)?;
    }
    
    Ok(())
}

/// Deletes a connection file from the target machine
pub fn delete_target_connection(config_dir: &Path, target_machine: &str, connection: &Connection) -> io::Result<()> {
    let connections_dir = config_dir.join(CONNECTIONS_DIR).join(target_machine);
    let filename = connection.target_filename();
    let path = connections_dir.join(filename);
    
    if path.exists() {
        fs::remove_file(path)?;
    }
    
    Ok(())
}

/// Lists all connection files for a machine
pub fn list_connection_files(config_dir: &Path, machine_name: &str) -> io::Result<Vec<PathBuf>> {
    let connections_dir = config_dir.join(CONNECTIONS_DIR).join(machine_name);
    
    if !connections_dir.exists() {
        return Ok(Vec::new());
    }

    let mut files = Vec::new();
    for entry in fs::read_dir(&connections_dir)? {
        let entry = entry?;
        let path = entry.path();
        if path.extension().and_then(|s| s.to_str()) == Some("json") {
            files.push(path);
        }
    }

    Ok(files)
}

/// Generates a unique connection ID based on source and target
pub fn generate_connection_id(from: &str, to: &str) -> String {
    // Sanitize the strings to create a valid filename
    let sanitize = |s: &str| -> String {
        s.replace("@", "_")
         .replace("/", "_")
         .replace(" ", "_")
    };
    
    format!("{}->{}", sanitize(from), sanitize(to))
}
